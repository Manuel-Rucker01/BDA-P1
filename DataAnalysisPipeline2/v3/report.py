CNAMES = {"lo30": "Long-only K=30 (5/sector, 6%/name)", "lo50": "Long-only K=50 (7/sector, 4%/name)",
          "ls40": "Long/short 40/40 sector-neutral (gross 1.6)", "legacy_top10": "Legacy top-5% gate, top-10",
          "ew_universe": "EW eligible universe (gross)", "spy": "SPY"}


def _pct(x, d=1):
    return "" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{100 * x:.{d}f}%"


def _f(x, d=2):
    return "" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{d}f}"


def perf_row(name, m):
    return {"book": CNAMES.get(name, name), "CAGR": _pct(m["cagr"]), "vol": _pct(m["vol"]),
            "Sharpe": _f(m["sharpe"]), "maxDD": _pct(m["max_dd"]), "IR vs SPY": _f(m["ir_spy"]),
            "IR vs EW": _f(m["ir_ew"]), "turnover/reb": _pct(m.get("turnover_m", float("nan")), 0),
            "hit (m>0)": _pct(m["hit_rate_m"], 0), "hit vs EW": _pct(m["hit_vs_ew_m"], 0)}


def signal_table(sig: dict) -> pd.DataFrame:
    rows = []
    for y, s in sig.items():
        rows.append({"year": y, "dates": int(s["n_dates"]), "mean IC": _f(s["mean_ic"], 4),
                     "NW t": _f(s["nw_t"]), "IC>0 weeks": _pct(s["pct_ic_pos"], 0),
                     "decile spread (30d)": _pct(s["decile_spread"], 2),
                     "sector-neutral IC": _f(s["sector_neutral_ic"], 4), "avg names": f"{s['avg_names']:.0f}"})
    return pd.DataFrame(rows)


def build(log=print) -> dict:
    res = json.load(open(ex.eval_dir("results.json")))
    V = res["variants"]
    sig_all = {v: {"mean_ic": V[v]["signal"]["fwd_ret_30"]["all"]["mean_ic"],
                   "nw_t": V[v]["signal"]["fwd_ret_30"]["all"]["nw_t"]} for v in V}
    variant = gate.choose_variant({v: s for v, s in sig_all.items() if v in gate.CANDIDATE_VARIANTS})
    perf_all = {c: V[variant]["perf"][c]["all"] for c in gate.CONSTRUCTIONS}
    construction = gate.choose_construction(perf_all)
    log(f"[report] chosen variant={variant} construction={construction}")
    trials = res["trials"]
    assert len(trials) == gate.N_TRIALS, f"expected {gate.N_TRIALS} trials, got {len(trials)}"
    boots = {c: ex.bootstrap_and_dsr(variant, c, trials) for c in gate.CONSTRUCTIONS}
    hp = ex.eval_dir(f"holdout_{variant}.json")
    if not os.path.exists(hp):
        ex.holdout_ic(variant, log=log)
    hold = json.load(open(hp))
    years_ic = {y: V[variant]["signal"]["fwd_ret_30"][y]["mean_ic"] for y in gate.A_YEARS
                if y in V[variant]["signal"]["fwd_ret_30"]}
    ew_sh = res["benchmarks"]["ew_universe"]["all"]["sharpe"]
    rows = gate.evaluate_gate(sig_all[variant], years_ic, perf_all[construction], ew_sh,
                              boots[construction]["dsr"]["dsr"], hold["mean_ic"])
    passed = all(r["pass"] for r in rows)
    out = {"variant": variant, "construction": construction, "gate": rows, "passed": passed,
           "holdout": hold, "bootstrap": boots, "sig_all": sig_all}
    json.dump(out, open(ex.eval_dir("gate.json"), "w"), indent=1, default=float)
    write_markdown(res, out)
    return out


def write_markdown(res: dict, g: dict) -> None:
    V = res["variants"]
    v, c = g["variant"], g["construction"]
    dmeta = json.load(open(os.path.join(ds.v3_dir("dataset"), "meta.json")))
    wf = {x: json.load(open(os.path.join(ds.v3_dir("wf"), f"{x}.json"))) for x in V}
    L = []
    L.append("# v3 model — walk-forward out-of-sample evaluation and promotion gate (WS3)\n")
    L.append(f"Generated by `DataAnalysisPipeline2/v3/report.py`. Data: `$BDA_DATA_V3/v3model/` "
             f"(prices through {dmeta['calendar_end']}). Plan: `docs/IMPROVEMENT_PLAN_v3.md` (WS3).\n")
    L.append("## Verdict\n")
    verdict = "**PASS — v3 is promotable**" if g["passed"] else "**FAIL — v3 is NOT promoted**"
    L.append(f"{verdict}. Chosen recipe: `{v}` (`{tr.VARIANTS[v][0]}`), chosen construction: "
             f"`{c}` — {CNAMES[c]}. The gate thresholds and both selection rules were committed in "
             f"`v3/gate.py` before any walk-forward result existed.\n")
    gt = pd.DataFrame([{"#": r["id"], "criterion": r["criterion"],
                        "value": (_f(r["value"], 4) if isinstance(r["value"], float) else r["value"]),
                        "threshold": r["threshold"], "result": "PASS" if r["pass"] else "FAIL"}
                       for r in g["gate"]])
    L.append(md_table(gt, index=False) + "\n")

    # ---------------------------------------------------------------- setup
    L.append("## Setup\n")
    L.append("* **Universe / eligibility (PIT):** WS1 survivorship-free common stocks (NASDAQ/NYSE/AMEX, "
             "active + delisted, reused symbols split into `SYM~k`), eligible on a date when raw close "
             ">= $3, 20-session ADV >= $2M and >= 120 bars (`universe.eligible`). Cross-sectional "
             "features, z-scores and rank targets use exactly this population "
             "(`core.compute_features(..., population=...)` / `core.add_cross_sectional_features`).")
    L.append(f"* **Features:** the 32 `features/core.py` columns (price/volume only; fundamentals not "
             f"yet available — WS2 blocked on `SEC_USER_AGENT`), z-scored per date with "
             f"`core.cross_sectional_zscore` over eligible names. No KG in the candidate recipes.")
    sec = {y: dmeta["years"][y]["sector_source_eligible"] for y in dmeta["years"]}
    sec_mean = pd.DataFrame(sec).T.mean()
    L.append(f"* **Sectors:** the legacy metadata labels only {dmeta['n_known_sector_tickers']:,} tickers; "
             f"among eligible rows {_pct(sec_mean.get('meta', 0))} have a real label, "
             f"{_pct(sec_mean.get('proxy', 0))} get a **proxy sector** (known sector with the highest "
             f"market-residual return correlation over the {ds.PROXY_WINDOW} sessions before the month, "
             f"recomputed monthly, PIT) and {_pct(sec_mean.get('none', 0), 2)} stay 'Unknown'. Sector "
             f"features, sector-neutral targets/IC and every sector cap use this effective sector.")
    L.append(f"* **Labels:** forward 21/30-session returns on adjusted closes; a stock that stops trading "
             f"inside the horizon gets the return to its last close (delisting losses count); winsorized "
             f"to {ds.LABEL_CLIP}; targets = per-date percentile ranks over eligible names "
             f"(raw, or sector-demeaned for `sn30`).")
    L.append(f"* **Model:** LightGBM + XGBoost + CatBoost regressors, fixed moderate hyperparameters, "
             f"each early-stopped on the last <=52 weekly dates of its training window (fit part ends "
             f"{tr.EMBARGO_SESSIONS} sessions before validation), refit on the whole window with the "
             f"early-stopped tree count, rank-averaged per date.")
    L.append(f"* **Walk-forward:** weekly decision dates (last session of each week) from 2017; test year "
             f"Y in 2019..2026 trained on dates t with pos(t) < pos(first session of Y) − "
             f"{tr.EMBARGO_SESSIONS} (embargo ≥ 30 + 10 sessions). Every 2019–2026 weekly prediction is "
             f"out of sample.")
    L.append(f"* **Backtest:** monthly rebalance on the first session of each month using the latest weekly "
             f"OOS prediction strictly before it, traded at that close; daily mark-to-market; delisted "
             f"holdings frozen at their last close and sold at the next rebalance; {bt.COST_BPS:.0f} bps "
             f"per side on traded notional; {bt.BORROW_BPS_YR / 100:.0f}%/yr borrow on shorts; cash at 0%; "
             f"daily stock returns clipped to {bt.RET_CLIP} only where the adjusted and raw returns disagree "
             f"(corporate-action / adjustment-error days; genuine moves count in full). Period: first rebalance Feb 2019 → "
             f"{dmeta['calendar_end']}. EW benchmark = all eligible names, monthly, no costs; SPY = Alpaca "
             f"SIP adjusted.\n")
    folds = pd.DataFrame([{"test year": f["year"], "train dates": f"{f['train_range'][0]} → {f['train_range'][1]}",
                           "rows": f"{f['n_train_rows']:,}", "ES val": f"{f['val_range'][0]} → {f['val_range'][1]}",
                           **{f"trees {k}": n for k, n in f["best_iter"].items()}} for f in wf[v]["folds"]])
    L.append(f"Folds of `{v}`:\n\n" + md_table(folds, index=False) + "\n")

    # --------------------------------------------------------------- signal
    L.append(f"## Signal — `{v}` (weekly OOS, vs 30-session return, eligible universe)\n")
    L.append(md_table(signal_table(V[v]["signal"]["fwd_ret_30"]), index=False) + "\n")
    L.append("NW t uses 6 lags (30-session labels overlap ~6 weekly dates). Sector-neutral IC = within-sector "
             "Spearman averaged over effective sectors with >= 20 names ('Unknown' excluded).\n")

